"""Command line: validate calendar data, inspect days, and build .ics feeds."""

from __future__ import annotations

import argparse
import datetime as dt
import sys
from collections import Counter
from pathlib import Path

from .carpool import build_carpool_feed, is_carpool_file, load_carpool, occurrences
from .combine import build_person_feed, is_person_file, load_person
from .ical import build_feed, build_student_feed
from .model import CalendarError, load_school
from .resolve import resolve_days


def cmd_check(args) -> int:
    for path in args.files:
        if is_carpool_file(path):
            cp = load_carpool(path)
            occ = occurrences(cp)
            print(f"Carpool — {path}\n  {len(cp.rules)} rules, {len(occ)} pickups; "
                  f"feeds: {', '.join(f.id for f in cp.feeds)}")
            continue
        if is_person_file(path):
            person = load_person(path)
            parts = [f"{s.school.id}/{s.feed or s.student}" for s in person.sources]
            print(f"{person.name} ({person.id}) — {path}\n  combines: {', '.join(parts)}")
            continue
        school = load_school(path)
        days = resolve_days(school)
        session = [d for d in days if d.in_session]
        print(f"{school.name} ({school.id}) — {path}")
        print(f"  {school.first_day} → {school.last_day}: {len(session)} school days")
        by_sched = Counter(d.schedule.name for d in session)
        for name, n in by_sched.most_common():
            print(f"    {n:4d}  {name}")
        if school.rotation:
            by_rot = Counter(d.rotation for d in session if d.rotation)
            print("  rotation: " + ", ".join(f"{k}={v}" for k, v in sorted(by_rot.items())))
        print(f"  {len(school.events)} events, {len(school.overrides)} day overrides")
        print(f"  feeds: {', '.join(f.id for f in school.feeds) or '(none)'}")
        if school.students:
            print(f"  student feeds: {', '.join(s.id for s in school.students)}")
    return 0


def cmd_day(args) -> int:
    school = load_school(args.file)
    target = dt.date.fromisoformat(args.date)
    for d in resolve_days(school):
        if d.date != target:
            continue
        print(f"{d.date} ({d.date:%A})")
        if not d.in_session:
            print("  No school" + (f" — {', '.join(d.titles)}" if d.titles else ""))
            return 0
        print(f"  {d.schedule.name}" + (f" · {d.rotation} Day" if d.rotation else ""))
        for t in d.titles:
            print(f"  note: {t}")
        for p in d.schedule.periods:
            print(f"  {p.start:%H:%M}–{p.end:%H:%M}  {p.name_for(d.rotation)}"
                  + ("" if p.kind == "class" else f" ({p.kind})")
                  + (f"  [group {p.group}]" if p.group else ""))
        return 0
    print(f"{target} is outside {school.first_day}..{school.last_day}", file=sys.stderr)
    return 1


def cmd_build(args) -> int:
    out = Path(args.out)
    for path in args.files:
        if is_carpool_file(path):
            cp = load_carpool(path)
            (out / "carpool").mkdir(parents=True, exist_ok=True)
            for f in cp.feeds:
                _write(out / "carpool" / f"{f.id}.ics", build_carpool_feed(cp, f))
            continue
        if is_person_file(path):
            person = load_person(path)
            (out / "people").mkdir(parents=True, exist_ok=True)
            _write(out / "people" / f"{person.id}.ics", build_person_feed(person))
            continue
        school = load_school(path)
        days = resolve_days(school)
        dest = out / school.id
        dest.mkdir(parents=True, exist_ok=True)
        for feed in school.feeds:
            _write(dest / f"{feed.id}.ics", build_feed(school, feed, days=days))
        for student in (s for s in school.students if s.publish):
            _write(dest / f"{student.id}.ics", build_student_feed(school, student, days=days))
    return 0


def _write(path: Path, cal) -> None:
    data = cal.to_ical()
    if path.exists() and path.read_bytes() == data:
        return
    path.write_bytes(data)
    print(f"wrote {path}")


START, END = "<!-- feeds:start -->", "<!-- feeds:end -->"


def render_links(files, out: str, base_url: str) -> str:
    base_url = base_url.rstrip("/")
    lines = [
        START,
        "<!-- Generated by `sbtical readme`; edit the YAML in data/, not this section. -->",
        "",
    ]
    def link(name, desc, url):
        lines.append(f"**{name}**" + (f" — {desc}" if desc else ""))
        lines.extend(["", "```", url.replace("https://", "webcal://", 1), "```", ""])

    carpools = [p for p in files if is_carpool_file(p)]
    people = [p for p in files if p not in carpools and is_person_file(p)]
    schools = [p for p in files if p not in carpools and p not in people]
    kids = []
    for path in schools:
        school = load_school(path)
        if school.feeds:
            lines += [f"### {school.name}", ""]
        for f in school.feeds:
            link(f.name, f.description, f"{base_url}/{out}/{school.id}/{f.id}.ics")
        for s in school.students:
            if s.publish:
                kids.append((s.name, s.description, f"{base_url}/{out}/{school.id}/{s.id}.ics"))
    for path in people:
        person = load_person(path)
        kids.append((person.name, person.description, f"{base_url}/{out}/people/{person.id}.ics"))
    if kids:
        lines += ["### Class Schedules", ""]
        for name, desc, url in sorted(kids):
            link(name, desc, url)
    for path in carpools:
        lines += ["### Carpool", ""]
        for f in load_carpool(path).feeds:
            link(f.name, f.description, f"{base_url}/{out}/carpool/{f.id}.ics")
    lines.append(END)
    return "\n".join(lines)


def cmd_readme(args) -> int:
    readme = Path(args.readme)
    text = readme.read_text()
    if START not in text or END not in text:
        print(f"error: {readme} needs {START} and {END} markers", file=sys.stderr)
        return 2
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    new = head + render_links(sorted(args.files), args.out, args.base_url) + tail
    if new != text:
        readme.write_text(new)
        print(f"updated {readme}")
    return 0


def cmd_site(args) -> int:
    from .site import build_site

    build_site(sorted(args.files), Path(args.out), Path(args.feeds), Path(args.config))
    return 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="sbtical", description=__doc__)
    sub = ap.add_subparsers(dest="cmd", required=True)

    p = sub.add_parser("check", help="validate data files and print a summary")
    p.add_argument("files", nargs="+")
    p.set_defaults(func=cmd_check)

    p = sub.add_parser("day", help="show how a single date resolves")
    p.add_argument("file")
    p.add_argument("date", help="YYYY-MM-DD")
    p.set_defaults(func=cmd_day)

    p = sub.add_parser("build", help="write .ics feeds")
    p.add_argument("files", nargs="+")
    p.add_argument("-o", "--out", default="feeds")
    p.set_defaults(func=cmd_build)

    p = sub.add_parser("readme", help="rewrite the subscribe-links section of README.md")
    p.add_argument("files", nargs="+")
    p.add_argument("--readme", default="README.md")
    p.add_argument("--out", default="feeds", help="feed directory, relative to repo root")
    p.add_argument(
        "--base-url",
        default="https://aaronj84.github.io/saved-by-the-ical",
    )
    p.set_defaults(func=cmd_readme)

    p = sub.add_parser("site", help="build the static GitHub Pages site")
    p.add_argument("files", nargs="+")
    p.add_argument("-o", "--out", default="_site")
    p.add_argument("--feeds", default="feeds", help="built feeds to copy into the site")
    p.add_argument("--config", default="data/site.yaml", help="site view configuration")
    p.set_defaults(func=cmd_site)

    args = ap.parse_args(argv)
    try:
        return args.func(args)
    except CalendarError as e:
        print(f"error: {e}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
